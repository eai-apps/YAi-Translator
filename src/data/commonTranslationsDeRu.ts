/** Быстрый поиск русского перевода немецкого слова или леммы. */
export function getGermanTranslation(lemma: string): string | undefined {
  if (!lemma) return undefined;
  if (COMMON_DE_RU[lemma]) return COMMON_DE_RU[lemma];
  const cap = lemma.charAt(0).toUpperCase() + lemma.slice(1);
  if (COMMON_DE_RU[cap]) return COMMON_DE_RU[cap];
  const lower = lemma.toLowerCase();
  if (COMMON_DE_RU[lower]) return COMMON_DE_RU[lower];
  return undefined;
}

/** Обратный поиск: найти немецкие слова по русскому запросу (поиск по вхождению). */
export function searchGermanByRussian(ruQuery: string, limit = 8): Array<{ lemma: string; translation: string }> {
  const clean = ruQuery.trim().toLowerCase();
  if (!clean || clean.length < 2) return [];

  const results: Array<{ lemma: string; translation: string }> = [];

  for (const [lemma, tr] of Object.entries(COMMON_DE_RU)) {
    const trLower = tr.toLowerCase();
    if (trLower === clean || trLower.startsWith(clean) || trLower.includes(clean)) {
      results.push({ lemma, translation: tr });
      if (results.length >= limit) break;
    }
  }

  return results;
}
